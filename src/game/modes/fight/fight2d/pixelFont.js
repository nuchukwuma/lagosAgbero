/** Width of a line of text in pixels (3 per letter plus 1 between). */
export const textWidth = (text) => Math.max(0, String(text).length * 4 - 1)

/** Draw text with its top-left at (x, y), one canvas unit per pixel. */
export function pixelText(g, text, x, y, color) {
  g.fillStyle = color
  let cx = Math.round(x)
  for (const ch of String(text).toUpperCase()) {
    const rows = G[ch] || G[' ']
    for (let r = 0; r < 5; r++) for (let c = 0; c < 3; c++) if (rows[r][c] === '1') g.fillRect(cx + c, Math.round(y) + r, 1, 1)
    cx += 4
  }
}
