const WORDS = new RegExp(`\\b(${Object.keys(SAY).sort((a, b) => b.length - a.length).join('|')})\\b`, 'gi')

/** Respell the Nigerian words in a line so an English voice says them right. */
export function respell(text) {
  return text
    .replace(WORDS, (w) => SAY[w.toLowerCase()]) // voices run hyphenated syllables together smoothly
    .replace(/(^|[\s,])o([!.?,]|$)/gi, '$1oh$2') // the Nigerian "o" at the end of a phrase
}
