// Checks src/assets/assetManifest.js against the files in public/assets and
// writes docs/asset-table.md (game name, file, size, planned use).
//
// Usage: npm run assets:check
//
// It loads the manifest through Vite so the manifest can stay a normal
// browser module (it imports JSON, which plain Node needs extra syntax for).

import fs from 'node:fs'
import path from 'node:path'
import { createServer } from 'vite'

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
const PUBLIC_ASSETS = path.join(ROOT, 'public', 'assets')

function walk(dir, base = dir) {
  if (!fs.existsSync(dir)) return []
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
    const p = path.join(dir, d.name)
    return d.isDirectory() ? walk(p, base) : [path.relative(base, p).split(path.sep).join('/')]
  })
}

const kb = (bytes) => `${Math.round(bytes / 1024)} KB`
const dims = (size) => size.map((v) => v.toFixed(1)).join(' × ')

async function main() {
  const server = await createServer({ root: ROOT, logLevel: 'error', server: { middlewareMode: true }, appType: 'custom' })
  try {
    const m = await server.ssrLoadModule('/src/assets/assetManifest.js')
    const onDisk = new Set(walk(PUBLIC_ASSETS))
    const referenced = new Set(m.allManifestFiles())

    const missing = [...referenced].filter((f) => !onDisk.has(f))
    const unusedGlb = [...onDisk].filter((f) => f.endsWith('.glb') && !referenced.has(f)).sort()

    const rows = Object.keys(m.MODELS).map((name) => {
      const a = m.getAsset(name)
      const bytes = fs.existsSync(path.join(PUBLIC_ASSETS, a.file)) ? fs.statSync(path.join(PUBLIC_ASSETS, a.file)).size : 0
      return { name, category: a.category, file: a.file, size: bytes ? kb(bytes) : 'MISSING', dims: dims(a.size), use: a.use }
    })

    const lines = []
    lines.push('# Asset table', '')
    lines.push('Generated by `npm run assets:check` from `src/assets/assetManifest.js`.')
    lines.push('Sizes in metres are after pack scaling (1 unit = 1 m).', '')
    const cats = [...new Set(rows.map((r) => r.category))]
    for (const cat of cats) {
      lines.push(`## ${cat}`, '', '| Game name | File | Download | W × H × L (m) | Planned use |', '|---|---|---|---|---|')
      for (const r of rows.filter((x) => x.category === cat)) {
        lines.push(`| \`${r.name}\` | \`${r.file}\` | ${r.size} | ${r.dims} | ${r.use} |`)
      }
      lines.push('')
    }
    lines.push('## Characters', '', '| Game name | File | Download | Planned use |', '|---|---|---|---|')
    const charFile = (label, f, use) => {
      const p = path.join(PUBLIC_ASSETS, f)
      lines.push(`| ${label} | \`${f}\` | ${fs.existsSync(p) ? kb(fs.statSync(p).size) : 'MISSING'} | ${use} |`)
    }
    for (const [k, b] of Object.entries(m.CHARACTER.bodies)) charFile(`body: ${k}`, b.file, `Outfit body (${b.source}); parts: ${b.parts.map((p) => p.name).join(', ')}`)
    for (const [k, e] of Object.entries(m.EXTRA_MODELS)) charFile(`extra: ${k}`, e.file, k === 'bus' ? 'Molue / BRT-style bus (Kenney has no bus)' : '')
    lines.push('', '## Retargeted Mixamo animations', '', '`npm run assets:animations` builds these from your Mixamo FBX files.', '', '| Clip | Source file | Length | Loop | Root motion | Download | Planned use |', '|---|---|---|---|---|---|---|')
    for (const [k, c] of Object.entries(m.CHARACTER.clips)) {
      const p = path.join(PUBLIC_ASSETS, c.file)
      lines.push(`| \`${k}\` | ${c.source} | ${c.duration.toFixed(2)} s | ${c.loop ? 'yes' : 'no'} | ${c.rootMotion.speed} m/s | ${fs.existsSync(p) ? kb(fs.statSync(p).size) : 'MISSING'} | ${c.use} |`)
    }
    lines.push('', '## Built in code (no model of their own)', '', '| Name | Uses | How |', '|---|---|---|')
    for (const [k, v] of Object.entries(m.PROCEDURAL)) lines.push(`| \`${k}\` | ${v.parts.map((p) => `\`${p}\``).join(', ') || '—'} | ${v.use} |`)
    lines.push('', '## GLB files on disk not used yet', '', unusedGlb.length ? unusedGlb.map((f) => `- \`${f}\``).join('\n') : '_none_', '')

    fs.mkdirSync(path.join(ROOT, 'docs'), { recursive: true })
    fs.writeFileSync(path.join(ROOT, 'docs', 'asset-table.md'), lines.join('\n'))

    const totalBytes = [...onDisk].reduce((s, f) => s + fs.statSync(path.join(PUBLIC_ASSETS, f)).size, 0)
    console.log(`Manifest entries: ${rows.length} models, ${Object.keys(m.PROCEDURAL).length} procedural recipes`)
    console.log(`Files in public/assets: ${onDisk.size} (${(totalBytes / 1024 / 1024).toFixed(1)} MB)`)
    console.log(`Unused GLBs: ${unusedGlb.length}`)
    console.log('Wrote docs/asset-table.md')
    if (missing.length) {
      console.error(`\nMISSING files referenced by the manifest (${missing.length}):`)
      for (const f of missing) console.error(`  - ${f}`)
      process.exitCode = 1
    } else {
      console.log('OK: every manifest file exists.')
    }
  } finally {
    await server.close()
  }
}

main()
